; the name and file format for the assembled program

		!to "outrun-petscii.prg",cbm

; claw in the binary data...
		
		* = $2000
		!binary "data/font.chr"
		
		* = $b000
music	!binary "data\music.prg",,2

; label assignments for keyboard control

cpra				= $dc00				; cia #1, port register a
cprb				= $dc01				; cia #1, port register b

; some more label assignments (variables)

sync				= $50				; interupt sync variable
video_type			= $51				; 0=pal, 1=ntsc
music_tmr			= $52				; timer for music frame skip on ntsc		


; add a BASIC startline - generate sys 2066

		* = $0801
		!word entry-2
		!byte $00,$00,$9e
		!text "2066"
		!byte $00,$00,$00


; entry point at $0812 (sys 2066!)

		* = $0812

entry

; detect what machine type is being used...

start_scan
		lda $d012
chkntsc
		cmp $d012
		beq chkntsc
		bmi start_scan
		adc #$00
		lsr
		bcs isntsc
		lsr
		bcs isoldntsc
		ldx #$00					; check drean or pal
		lda #$10
chkpal
		inx
		cmp $d012
		bne chkpal
		cpx #$70
		bcc ispal
isdrean
		lda #$01
		sta video_type				; video = ntsc
		jmp detect_dun
isntsc	
		lda #$01
		sta video_type				; video = ntsc
		jmp detect_dun
isoldntsc
		lda #$01
		sta video_type				; video = ntsc
		jmp detect_dun
ispal
		lda #$00
		sta video_type				; video = pal

detect_dun
		lda #$35					; kill EVERYTHING (MWHAHA!) except $f000-$ffff
		sta $01

; stop interrupts, disable the roms and set up nmi and irq interrupt pointers	

		sei							; disable maskable IRQs		
		
; setup nmi

		lda #<nmi
		sta $fffa
		lda #>nmi
		sta $fffb
		
; setup irq's

		lda #<int
		sta $fffe
		lda #>int
		sta $ffff

		lda #$7f
		sta $dc0d			; disable timer interrupts which can be generated by the two CIA chips
		sta $dd0d			; the kernal uses such an interrupt to flash the cursor and scan the keyboard, so we better stop it

		lda $dc0d			; by reading this two registers we negate any pending CIA irqs.
		lda $dd0d			; if we don't do this, a pending CIA irq might occur after we finish setting up our irq. we don't want that to happen.

		lda #$00			; where raster starts on screen, usually at top but can be different
		sta $d012

		lda #$1b			; as there are more than 256 rasterlines, the topmost bit of $d011 serves as
		sta $d011			; the 9th bit for the rasterline we want our irq to be triggered.
		
		lda #$01
		sta $d019			; clear interupt bit
		sta $d01a			; tell vicii to generate interupt

		lda #$35			; turn off basic and kernal rom thus
		sta $01				; c64 now sees RAM everywhere except at $d000-$e000
		
		lda #$03			; select video bank
		sta $dd00		
						
		lda #$18			; use our custom charset (lowecase rom)
		sta $d018

		cli
		
; prepare the music	

		lda #$01
		jsr music+$219		
		
; setup the screen for the very first run

		jsr clear_screen			; clear screen with subroutine

; print intro message		
				
		ldx #$00
text_loop
		lda intro_1,x				; pull in the data for the
		sta $0590,x					; 3 line 'intro' text
		lda intro_2,x				; and print it on screen!
		sta $05e0,x		
		lda intro_3,x
		sta $0630,x			
	
		lda #$01					; colour those lines!
		sta $d990,x
		lda #$0f		
		sta $d9e0,x
		lda #$0c		
		sta $da30,x		

		inx
		cpx #$28
		bne text_loop

; give time to read the intro	
						
		ldy #$ff					; wait a bit...
		jsr sync_wait_long	

		jsr clear_screen			; clear screen with subroutine
		
; print up the main screen ram			
		
		ldx #$00					; zero x register
scrnram_loop						; load up whatver is in the screen
		lda screen_ram,x			; ram table and write to the
		sta $0400,x					; screen ram
		lda screen_ram+250,x
		sta $0400+250,x
		lda screen_ram+500,x
		sta $0400+500,x
		lda screen_ram+750,x
		sta $0400+750,x	
		inx
		cpx #$fa					; done 250 writes?
		bne scrnram_loop			; all written? no? loop back!
		
; print the compressed title screen colour data to colour ram
			
		ldx #$00					; zero x register
		ldy #$00					; zero y register
colram_loop
		lda colour_ram,x			; load up a byte
		sta $d800+1,y				; store a nybble to screen
		lsr
		lsr
		lsr
		lsr
		sta $d800,y					; store the other nybble

		lda colour_ram+125,x
		sta $d800+251,y
		lsr
		lsr
		lsr
		lsr
		sta $d800+250,y

		lda colour_ram+250,x
		sta $d800+501,y
		lsr
		lsr
		lsr
		lsr
		sta $d800+500,y

		lda colour_ram+375,x
		sta $d800+751,y
		lsr
		lsr
		lsr
		lsr
		sta $d800+750,y

		iny
		iny
		inx
		cpx #$7d
		bne colram_loop			
		
; main loop to detect keypresses

mainloop

		jsr sync_wait				; wait until irq finishes!

; check if 's' is pressed for 'splash wave' music

		lda #$fd 					; load $dc00...
		sta cpra					; ...with bit row 1
		
		lda cprb					; load $dc01 to test...
		cmp #$df					; key 's' pressed?
		bne check_m					; no? check 'm'
		
		jsr key_debounce			; debounce the keyboard!
		
		lda #$01
		jsr music+$219
		
		jmp kcheck_dun		
		

; check if 'm' is pressed for 'magical sound shower' music

check_m	
		lda #$ef 					; load $dc00...
		sta cpra					; ...with bit row 4
		
		lda cprb					; load $dc01 to test...
		cmp #$ef					; key 'm' pressed?
		bne check_space
		
		jsr key_debounce
		
		lda #$00
		jsr music+$219
		
		jmp kcheck_dun	
		
; check if 'm' is pressed for 'magical sound shower' music	

check_space
		lda #$7f 					; load $dc00...
		sta cpra					; ...with bit row 7
		
		lda cprb					; load $dc01 to test...
		cmp #$ef					; key 'm' pressed?
		bne kcheck_dun
		
		jsr key_debounce
		jmp exit_demo
		
kcheck_dun			
		jmp mainloop
	
; space has been pressed so reset some registers

exit_demo
		sei
		lda #$37
		sta $01

		lda #$00
		sta $d011
		sta $d020
		sta $d021
		sta $d418

; reset the C64

		jmp $fce2			
												

; irq interrupt =================================

int
		pha  
		txa
		pha
		tya
		pha

		lda $d019
		and #$01
		sta $d019

; play some music!

		lda video_type				; what machine is being used
		cmp #$00					; PAL?
		beq call_music_driver		; yes? play the music!
									; no?
		ldx music_tmr				; load music timer
		inx							; increase it
		cpx #$08					; is it 8?
		bne	music_play				; no? play music!
									; yes?
		ldx #$00					; reset the timer
		stx music_tmr				; then skip playing
									; the music on this occasion
		jmp set_sync				; to slow it for ntsc!

music_play
		stx	music_tmr
		
call_music_driver
		jsr music+$69

; set sync variable for main line code synchronisation

set_sync
		lda #$01					; set the sync flag to '1'		
		sta sync					; so the main code runs!
		
		pla
		tay
		pla
		tax
		pla
nmi		rti

; end irq interrupt =============================


; subroutines ===================================


; clear the screen!

clear_screen
        lda #$00
		sta $d020
		sta $d021
		tax
		lda #$20
clsloop
		sta $0400,x
		sta $0500,x
		sta $0600,x
		sta $0700,x
		dex
		bne clsloop

		rts

; debounce subroutines for keyboard -------------------

key_debounce		
		lda cprb						; is there a keypress still?
		cmp #$ff						; an idiot is still pressing something???
		bne key_debounce				; lock them in a loop till they stop!!
		
		rts	

; irq sync wait subroutine ---------------------------------- 
	   	 
sync_wait								; wait for sync update in irq code!
		lda #$00						; waits until the sync flag is
		sta sync						; set at the end of the interupt
sw_loop									; code further down.
		cmp sync						; no code in the main loop above
		beq sw_loop						; is executed until the interupt
										; has run it's course!
		rts

; a sync wait delay subroutine ---------------------------------- 		
		
sync_wait_long						
		jsr sync_wait
		dey
		bne sync_wait_long

		rts							
			   	
; end subroutines ===============================


